#!/bin/bash
# omarchy-passkey-broker install script.
#
# Installs a single-user daemon that any local app can ask for a passkey, plus the qutebrowser
# bridge. The daemon runs as a systemd --user service so a passkey is available the moment the
# session is up, without a per-app integration.
#
#   ./install.sh                 install / update everything
#   ./install.sh --uninstall     remove what this script installed, and only that
#
# Re-run this script to update: it is idempotent.

set -euo pipefail

PLUGIN_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ID="Maximilian-Maag.passkey-broker"
DEST="${XDG_CONFIG_HOME:-$HOME/.config}/omarchy/plugins/$ID"
BIN="${HOME}/.local/bin"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT="$UNIT_DIR/passkey-broker.service"
GREASE_DATA="${XDG_DATA_HOME:-$HOME/.local/share}/qutebrowser/greasemonkey"
GREASE_CONFIG="${XDG_CONFIG_HOME:-$HOME/.config}/qutebrowser/greasemonkey"
WRAPPER_MARKER="# omarchy-passkey-broker: wrapper, safe to delete"
UNIT_MARKER="# generated by omarchy-passkey-broker install.sh"
BRIDGE_MARKER="@namespace    Maximilian-Maag.passkey-broker"
source "$PLUGIN_DIR/tools/venv_path.sh"
VENV="$(broker_venv_dir)"

say() { printf '  %s\n' "$1"; }
warn() { printf 'WARNING: %s\n' "$1" >&2; }

uninstall() {
  echo "omarchy-passkey-broker: uninstalling from $PLUGIN_DIR"

  # ── systemd --user service ────────────────────────────────────────────────────
  # Disabled before the unit is removed (a removed unit that is still enabled leaves a dangling
  # enable symlink), and only when the first line says the unit is ours. Every systemctl call is
  # best-effort: an uninstall on a machine with no session bus must still remove the files.
  if [[ -f $UNIT ]] && head -1 "$UNIT" | grep -qF "$UNIT_MARKER"; then
    if command -v systemctl >/dev/null; then
      systemctl --user disable --now passkey-broker.service >/dev/null 2>&1 || true
    fi
    rm -f "$UNIT"
    say "removed $UNIT"
    if command -v systemctl >/dev/null; then
      systemctl --user daemon-reload >/dev/null 2>&1 || true
    fi
  elif [[ -f $UNIT ]]; then
    warn "$UNIT is not ours — left alone."
  fi

  # ── CLI wrappers ──────────────────────────────────────────────────────────────
  local w
  for w in passkey-broker passkey-bridge-build; do
    if [[ -f $BIN/$w ]] && grep -qF "$WRAPPER_MARKER" "$BIN/$w"; then
      rm -f "$BIN/$w"
      say "removed $BIN/$w"
    elif [[ -e $BIN/$w ]]; then
      warn "$BIN/$w is not ours — left alone."
    fi
  done

  # ── the rendered bridge (the userscript in both greasemonkey dirs) ─────────────
  # The rendered script carries the userscript header, so the marker identifies ours: a
  # hand-written qute-passkey.js a user dropped there is left as it is.
  local dir dest
  for dir in "$GREASE_DATA" "$GREASE_CONFIG"; do
    dest="$dir/qute-passkey.js"
    if [[ -f $dest ]] && grep -qF "$BRIDGE_MARKER" "$dest"; then
      rm -f "$dest"
      say "removed $dest"
    elif [[ -e $dest ]]; then
      warn "$dest is not ours — left alone."
    fi
  done

  # ── the plugin copy ───────────────────────────────────────────────────────────
  if [[ -d $DEST ]]; then
    rm -rf "$DEST"
    say "removed $DEST"
  fi

  # The venv and the credential store are NOT install artifacts to reverse silently: the venv is
  # the daemon's runtime (rebuilt on the next install), and the store holds the user's private
  # keys. Both are left in place on purpose.
  echo ""
  echo "Done. The venv ($VENV) and the credential store under the state dir are left in place."
}

if [[ ${1:-} == --uninstall ]]; then
  uninstall
  exit 0
fi

echo "omarchy-passkey-broker: installing from $PLUGIN_DIR"

# ── 0. Validate the manifest ──────────────────────────────────────────────────
if command -v omarchy >/dev/null 2>&1; then
  omarchy plugin validate "$PLUGIN_DIR"
fi

# ── 1. Copy plugin files ──────────────────────────────────────────────────────
mkdir -p "$DEST"
cp -r "$PLUGIN_DIR/bin" "$PLUGIN_DIR/userscripts" "$DEST/"
cp "$PLUGIN_DIR/manifest.json" "$PLUGIN_DIR/README.md" "$DEST/"
cp "$PLUGIN_DIR/policy.json" "$DEST/" 2>/dev/null || true
chmod +x "$DEST/bin/passkey-broker" "$DEST/bin/passkey-bridge-build"
echo "  Plugin files -> $DEST"

# ── 2. Runtime dependencies in a private venv ─────────────────────────────────
# The daemon needs 'cryptography' (ES256) and 'fido2' (CTAP2). The system Python on Omarchy
# ships neither, and a systemd --user service cannot rely on a shell PATH that might point at
# a mise/pyenv interpreter, so the deps go in a venv of their own and everything points at it
# explicitly. That is also what CI does, so the two stay in step.
#
# The venv lives OUTSIDE the plugin folder (tools/venv_path.sh explains why: a plugin folder with
# a symlink in it — and a venv always has .venv/lib64 — fails `omarchy plugin validate`, so the
# manager merges an update and then rolls it back).
#
# ensure_venv REBUILDS the venv when its interpreter can no longer import those deps — the trap
# a version manager springing its `latest` alias onto a new Python creates. A bare existence
# test is not enough and cost a night of crash-looping here; see tools/ensure_venv.sh.
source "$PLUGIN_DIR/tools/ensure_venv.sh"
LEGACY_VENV="$(broker_legacy_venv "$DEST")"
if [[ -e $LEGACY_VENV ]]; then
  rm -rf "$LEGACY_VENV"
  echo "  removed the venv that lived inside the plugin folder (it is at $VENV now)"
fi
mkdir -p "$(dirname "$VENV")"
ensure_venv "$VENV"
echo "  Dependencies OK: $("$VENV/bin/python" -c 'import cryptography;print("cryptography", cryptography.__version__)')"

# ── 3. CLI wrappers on PATH ───────────────────────────────────────────────────
mkdir -p "$BIN"
write_wrapper() {                       # write_wrapper <name>
  cat > "$BIN/$1" <<EOF
#!/bin/bash
$WRAPPER_MARKER
exec "$VENV/bin/python" "$DEST/bin/$1" "\$@"
EOF
  chmod +x "$BIN/$1"
}
write_wrapper passkey-broker
write_wrapper passkey-bridge-build
echo "  CLI wrappers -> $BIN/passkey-broker, $BIN/passkey-bridge-build"

# ── 4. systemd --user service ─────────────────────────────────────────────────
mkdir -p "$UNIT_DIR"
cat > "$UNIT" <<EOF
$UNIT_MARKER
[Unit]
Description=Omarchy passkey broker (WebAuthn authenticator)
After=graphical-session.target
# A broken daemon must FAIL, not spin. Without a limit, Restart=on-failure retries forever, so a
# start-time error (a venv that cannot import its deps, say) becomes an invisible 2-second crash
# loop that burns CPU for hours and leaves passkeys silently dead. Five tries in a minute is
# enough to ride out a real transient; past that the unit goes failed and \`systemctl --user
# status passkey-broker\` says so.
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
ExecStart=$VENV/bin/python $DEST/bin/passkey-broker serve
Restart=on-failure
RestartSec=2

[Install]
WantedBy=default.target
EOF
systemctl --user daemon-reload
systemctl --user enable passkey-broker.service
# `enable --now` STARTS an inactive unit but leaves a RUNNING one untouched, so re-running this
# script (the documented way to update) would keep serving the old code until a manual restart -
# which is how a fix can look applied and still not be live. restart does both jobs.
systemctl --user restart passkey-broker.service
echo "  Service enabled + restarted: passkey-broker.service"

# ── 5. Build the browser bridge with the live port/token ──────────────────────
"$BIN/passkey-bridge-build"

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo "Done. The broker is running; check it with:"
echo "  passkey-broker status"
echo "  passkey-broker info"
echo ""
echo "In qutebrowser, reload Greasemonkey scripts once with  :greasemonkey-reload"
echo "Then sign in to a site normally and register a NEW passkey when it offers one."
echo ""
echo "Note: an EXISTING passkey cannot be used \u2014 its private key is non-exportable by"
echo "design. Register a new passkey with the broker, then every later sign-in is passwordless."
